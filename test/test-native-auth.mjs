import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import discovery, { readNativeAuthPresence } from "../src/provider-discovery.js";

const env = { USERPROFILE: "C:/native-home", HOME: "/native-home" };
const read = value => async () => JSON.stringify(value);
test("API and OAuth store presence without provider/env key forwarding", async () => {
  assert.equal(await readNativeAuthPresence({ env: { ...env, OPENCODE_API_KEY: "stale-env-fixture" }, readFile: read({ opencode: { type: "api", key: "local-fixture-not-a-real-key" } }) }), "api-key");
  assert.equal(await readNativeAuthPresence({ env, readFile: read({ opencode: { type: "oauth", refresh: "refresh-fixture" } }) }), "oauth");
  assert.equal(await readNativeAuthPresence({ env, readFile: read({ opencode: { type: "oauth", access: "fixture", expires: Date.now() + 60000 } }) }), "oauth");
});
test("missing, malformed, empty and expired auth fail closed", async () => {
  for (const value of [{}, { opencode: { type: "api", key: " " } }, { opencode: { type: "oauth", access: "fixture", expires: 1 } }, { opencode: { type: "unknown", key: "fixture" } }]) {
    assert.equal(await readNativeAuthPresence({ env, readFile: read(value) }), undefined);
  }
  assert.equal(await readNativeAuthPresence({ env, readFile: async () => "not-json" }), undefined);
  assert.equal(await readNativeAuthPresence({ env, readFile: async () => { throw new Error("unreadable fixture"); } }), undefined);
});
test("cancellation rejects instead of publishing missing authentication", async () => {
  const ctl = new AbortController();
  ctl.abort();
  await assert.rejects(readNativeAuthPresence({ env, signal: ctl.signal, readFile: read({}) }), { name: "AbortError" });
});
test("XDG login path and synthetic result never expose credential bytes", async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "opencode-native-auth-"));
  const authDir = path.join(root, "opencode");
  await fs.mkdir(authDir);
  try {
    await fs.writeFile(path.join(authDir, "auth.json"), JSON.stringify({ opencode: { type: "api", key: "fixture-private-key" } }));
    const result = await discovery.prepareSyntheticAuth({ provider: "opencode-cli", env: { XDG_DATA_HOME: root } });
    assert.equal(result.mode, "api-key");
    assert.equal(Object.hasOwn(result, "nativeAuth"), false);
    assert.equal(JSON.stringify(result).includes("fixture-private-key"), false);
    assert.equal(await discovery.prepareSyntheticAuth({ provider: "opencode", env: { XDG_DATA_HOME: root } }), undefined);
    const manifest = JSON.parse(await fs.readFile(new URL("../openclaw.plugin.json", import.meta.url), "utf8"));
    assert.deepEqual(manifest.syntheticAuthRefs, ["opencode-cli"]);
    assert.equal(manifest.providerCatalogEntry, "./src/provider-discovery.js");
    assert.deepEqual(manifest.providers, ["opencode"]);
  } finally {
    // root is exclusively owned, generated by mkdtemp under the OS temp dir.
    await fs.rm(root, { recursive: true, force: true });
  }
});
